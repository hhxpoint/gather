import type { TextFormat } from '@gather/core/text-format';

export interface FileVersion {
  /** Modification time reported by the filesystem when the file was read. */
  mtimeMs: number;
  /** Byte length at the same point in time. */
  size: number;
  /** SHA-256 of the exact bytes on disk. */
  digest: string;
}

export interface OpenedFile extends FileVersion {
  path: string;
  name: string;
  /** Editor text with LF line endings and no BOM. */
  content: string;
  format: TextFormat;
}

export interface SavedFile extends FileVersion {
  path: string;
  name: string;
  format: TextFormat;
}

export interface SaveRequest extends FileVersion {
  path: string;
  content: string;
  format: TextFormat;
}

export interface SaveAsRequest {
  content: string;
  format: TextFormat;
  /** Old path/ID used to clear a recovery snapshot after Save As. */
  previousPath?: string | null;
  recoveryId?: string | null;
}

export type SaveOutcome =
  | { ok: true; file: SavedFile }
  | {
      ok: false;
      reason: 'conflict';
      message: string;
    };

export interface RecoverySnapshot {
  id: string;
  path: string | null;
  name: string;
  format: TextFormat;
  /** File version at the last open/save before this unsaved snapshot. */
  baseVersion: FileVersion | null;
  /** UTF-8 byte length of the editor text. */
  bytes: number;
  savedAt: string;
}

export interface RestoredRecovery extends RecoverySnapshot {
  content: string;
}

export interface RecoveryPayload {
  path: string | null;
  name: string;
  content: string;
  format: TextFormat;
  baseVersion: FileVersion | null;
  /** Required when path is null; generated by the renderer for untitled docs. */
  recoveryId?: string;
}

export type ExternalChange =
  | {
      type: 'changed';
      path: string;
      version: FileVersion;
    }
  | {
      type: 'removed';
      path: string;
    };

export interface WorkspaceFile {
  path: string;
  /** POSIX-style path relative to the workspace root, used for display and IPC. */
  relativePath: string;
  name: string;
}

export interface Workspace {
  root: string;
  name: string;
  files: WorkspaceFile[];
  /** True when depth/file limits stopped a complete recursive listing. */
  truncated: boolean;
}

export interface WorkspaceSearchOptions {
  query: string;
  caseSensitive: boolean;
  regex: boolean;
}

export interface WorkspaceSearchHit {
  relativePath: string;
  name: string;
  /** 1-based line number in the file. */
  line: number;
  /** 1-based UTF-16 column in the line, matching CodeMirror positions. */
  column: number;
  preview: string;
  /** Offset of the match inside `preview`. */
  previewMatchStart: number;
  matchLength: number;
  matchText: string;
}

export interface WorkspaceSearchResult {
  matches: WorkspaceSearchHit[];
  filesScanned: number;
  filesSkipped: number;
  truncated: boolean;
  timedOut: boolean;
  durationMs: number;
  /** Set for invalid patterns, timeouts or child-process failures. */
  error?: string;
}

export type WorkspaceRestoreResult =
  | { status: 'none' }
  | {
      status: 'restored';
      workspace: Workspace;
      /** Last listed file, or null when the workspace had no active file. */
      relativePath: string | null;
      /** True when the saved file is no longer in the folder. */
      fileMissing: boolean;
    }
  | { status: 'unavailable'; message: string };

export type ExportFormat = 'pdf' | 'html';

export interface DocumentExportRequest {
  format: ExportFormat;
  /** Current editor text, not the last saved copy. */
  markdown: string;
  /** Used for the document title and the save-dialog filename. */
  suggestedName: string;
}

export interface DocumentExportResult {
  canceled: boolean;
  path?: string;
  bytes?: number;
  /** Local images that could not be embedded; the export still completed. */
  warnings: string[];
}

