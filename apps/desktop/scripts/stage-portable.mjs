#!/usr/bin/env node
import { cp, mkdir, readFile, rename, rm, stat, writeFile, chmod } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const workspaceRoot = join(root, '..', '..');
const electronDist = join(workspaceRoot, 'node_modules', 'electron', 'dist');

const platform = process.platform;
const layout = platform === 'win32'
  ? {
      output: join(root, 'release', 'win-unpacked'),
      electronExe: 'electron.exe',
      appExe: 'Gather.exe',
    }
  : platform === 'linux'
    ? {
        output: join(root, 'release', 'linux-unpacked'),
        electronExe: 'electron',
        appExe: 'gather',
      }
    : null;

if (!layout) {
  throw new Error('stage-portable currently supports Windows and Linux. Use electron-builder for other targets.');
}

const statInfo = await stat(electronDist).catch(() => null);
if (!statInfo?.isDirectory()) {
  throw new Error(`Electron runtime not found at ${electronDist}. Run npm ci first.`);
}

const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const output = layout.output;
const appRoot = join(output, 'resources', 'app');

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await cp(electronDist, output, { recursive: true });

await rename(join(output, layout.electronExe), join(output, layout.appExe));
if (platform !== 'win32') {
  await chmod(join(output, layout.appExe), 0o755);
}
await rm(join(output, 'resources', 'default_app.asar'), { force: true });

await mkdir(appRoot, { recursive: true });
await cp(join(root, 'out'), join(appRoot, 'out'), { recursive: true });
await cp(join(workspaceRoot, 'LICENSE'), join(appRoot, 'LICENSE'));
await writeFile(join(appRoot, 'package.json'), `${JSON.stringify({
  name: 'gather',
  productName: 'Gather',
  version: packageJson.version,
  description: packageJson.description,
  author: packageJson.author,
  license: packageJson.license,
  main: 'out/main/index.js',
}, null, 2)}\n`, 'utf8');

await writeFile(join(root, 'release', 'STAGING-README.txt'), [
  'Gather portable staging directory',
  '',
  'This directory is generated by apps/desktop/scripts/stage-portable.mjs.',
  'It is an UNSIGNED smoke-test build, not a release artifact.',
  '',
  'Missing before public distribution:',
  '- Authenticode signing and timestamping',
  '- Installer/uninstaller (NSIS or portable launcher)',
  '- Custom application icon and file association',
  '- Auto-update manifest and rollback',
  '- Clean-VM install/uninstall test',
  '',
  `Generated: ${new Date().toISOString()}`,
  `App version: ${packageJson.version}`,
  `Platform: ${platform}`,
].join('\n'), 'utf8');

console.log(JSON.stringify({
  output,
  executable: join(output, layout.appExe),
  version: packageJson.version,
  platform,
}, null, 2));
